import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
const root = new URL('../plugins/tallyhand/skills/', import.meta.url);
const skills = readdirSync(root).sort().map(name => {
  if (!/^[a-z0-9-]+$/.test(name)) throw new Error('Invalid skill directory');
  const text = readFileSync(new URL(`${name}/SKILL.md`, root), 'utf8');
  const match = /^---\nname: ([a-z0-9-]+)\ndescription: ("[^\n]+")\n---\n/.exec(text);
  if (!match || match[1] !== name) throw new Error(`Unsupported skill frontmatter: ${name}`);
  const uri = `skill://tallyhand/${name}/SKILL.md`;
  const files = ['SKILL.md', 'agents/openai.yaml'].map(path => {
    const content = readFileSync(new URL(`${name}/${path}`, root), 'utf8');
    return { uri: `skill://tallyhand/${name}/${path}`, mimeType: path.endsWith('.md') ? 'text/markdown' : 'text/yaml', text: content };
  });
  return { uri, frontmatter: { name, description: JSON.parse(match[2]) }, resources: files.map(file => ({ uri: file.uri, digest: `sha256:${createHash('sha256').update(file.text).digest('hex')}` })), text, files };
});
if (skills.length !== 5) throw new Error('Expected five focused skills');
const output = '// Generated by scripts/build-agent-skills.mjs; edit plugin SKILL.md sources.\nexport const AGENT_SKILLS = '+JSON.stringify(skills,null,2)+' as const;\n';
const target = new URL('../cli/src/agent-skills.generated.ts', import.meta.url);
if (process.argv.includes('--check')) { if (readFileSync(target,'utf8') !== output) throw new Error('Regenerate agent skills'); }
else writeFileSync(target, output);
